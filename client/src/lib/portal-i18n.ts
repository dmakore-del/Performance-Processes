export const portalCopy = copy;

export type PortalCopyKey = keyof typeof copy.en;

export function translatePortal(language: "en" | "fr", key: string) {
  return copy[language][key as PortalCopyKey] || copy.en[key as PortalCopyKey] || key;
}

export function usePortalI18n() {
  const { language } = useLanguage();
  const fr = language === "fr";
  const t = (key: PortalCopyKey | string) => translatePortal(language, key);
  const locale = fr ? "fr-CA" : "en-CA";
  const formatDate = (value: string | Date | null | undefined, options?: Intl.DateTimeFormatOptions) =>
    value ? new Intl.DateTimeFormat(locale, options).format(new Date(value)) : t("Not available");
  const status = (value: string) => {
    const labels: Record<string, PortalCopyKey> = {
      active: "Active", "on-hold": "On Hold", completed: "Completed", pending: "Pending",
      "in-progress": "In Progress", overdue: "Overdue", paid: "Paid invoices", unpaid: "Unpaid",
      void: "Void", "on-track": "On Track", "needs-attention": "Needs Attention", "at-risk": "At Risk",
      inactive: "Inactive", paused: "Paused", new: "New", contacted: "Contacted", qualified: "Qualified",
      proposal: "Proposal", negotiation: "Negotiation", won: "Won", lost: "Lost",
    };
    return t(labels[value] || value);
  };
  const priority = (value: string) => t(({ high: "High", medium: "Medium", low: "Low", urgent: "Urgent" } as Record<string, PortalCopyKey>)[value] || value);
  const role = (value: string) => t(({ admin: "Administrator", staff: "Staff", client: "Client" } as Record<string, PortalCopyKey>)[value] || value);
  return { fr, locale, t, status, priority, role, formatDate };
}